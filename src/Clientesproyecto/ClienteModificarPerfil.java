    private void cargarDatosEnLaTabla() {
        Eventos eventos = new Eventos();
        DefaultTableModel model = eventos.obtenerModeloEventos(); // Asegúrate de que este método devuelva un modelo adecuado
        jTable1.setModel(model);
        
        model.addTableModelListener(new TableModelListener() {
            @Override
            public void tableChanged(TableModelEvent e) {
                if (e.getType() == TableModelEvent.UPDATE) {
                    int row = e.getFirstRow();
                    int column = e.getColumn();
                    if (column > 0) { // Asegura que el ID no sea editable
                        Object data = model.getValueAt(row, column);
                        String id = model.getValueAt(row, 0).toString();
                        String campo = obtenerNombreCampo(column);
                        eventos.actualizarEvento(id, campo, data);
                    }
                }
            }
        });
    }

    private String obtenerNombreCampo(int columna) {
        switch (columna) {
            case 1: return "nombre";
            case 2: return "tipo_evento";
            case 3: return "fecha";
            case 4: return "capacidad";
            case 5: return "precio";
            default: return null; // No debería ocurrir
        }
    }
    
