    private void btnIniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarActionPerformed
     // Obtener el ID y la contraseña desde los campos de texto.
    String id = txtId.getText();
    String contrasena = txtContraseña.getText();

    // Crear una instancia de la clase Administradores para verificar las credenciales.
    Administradores admin = new Administradores();
    Clientes cliente = new Clientes(); // Instanciar la clase Clientes

    // Llamar al método de inicio de sesión para verificar si las credenciales son correctas.
    if (id.startsWith("A") && admin.iniciarSesion(id, contrasena)) {
        // Si el ID comienza con 'A', abrir el frame de AdministradorPrincipal.
        AdministradorPrincipal adminFrame = new AdministradorPrincipal();
        adminFrame.setVisible(true);
        this.dispose(); // Cerrar la ventana actual
    } else if (cliente.iniciarSesion(id, contrasena)) {  // Verificación adicional para clientes
        // Si es un cliente, abrir el frame de ClientePrincipal.
        ClientePrincipal clienteFrame = new ClientePrincipal();
        clienteFrame.setVisible(true);
        this.dispose(); // Cerrar la ventana actual
    } else {
        // Si las credenciales no son correctas, mostrar un mensaje de error.
        JOptionPane.showMessageDialog(this, "ID o contraseña incorrecta. Por favor, intente de nuevo.");
    }
    }//GEN-LAST:event_btnIniciarActionPerformed

