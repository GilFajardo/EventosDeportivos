    private void jEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jEliminarActionPerformed
// Solicitar ID y contraseña del administrador
    String adminId = JOptionPane.showInputDialog(this, "Ingrese su ID de administrador:");
    String adminPassword = JOptionPane.showInputDialog(this, "Ingrese la contraseña del administrador para continuar:");
    
    if (adminId != null && adminPassword != null && !adminId.isEmpty() && !adminPassword.isEmpty()) {
        // Instancia de la clase Administradores para verificar la identidad
        Administradores admin = new Administradores();
        
        if (admin.iniciarSesion(adminId, adminPassword)) {
            // Si la identidad se verifica correctamente, proceder con la eliminación
            String id = jtxtID.getText();
            String apellido = jtxtApellido.getText();
            
            if (!id.isEmpty() && !apellido.isEmpty()) {
                Clientes clientes = new Clientes();
                clientes.eliminarCuentaCliente(id, apellido);
                
                // Actualizar la tabla después de la eliminación
                cargarDatos();
                JOptionPane.showMessageDialog(this, "Usuario eliminado correctamente.");
            } else {
                JOptionPane.showMessageDialog(this, "Por favor, complete los campos ID y Apellido.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "ID o contraseña incorrecta.", "Autorización Fallida", JOptionPane.ERROR_MESSAGE);
        }
    } else {
        JOptionPane.showMessageDialog(this, "Autorización cancelada o campos incompletos.", "Autorización Fallida", JOptionPane.INFORMATION_MESSAGE);
    }
    }//GEN-LAST:event_jEliminarActionPerformed


