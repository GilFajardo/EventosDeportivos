    private void jBtnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnAgregarActionPerformed
        String dia = jTextDia.getText();
        String anio = jTextAño.getText();
        String mes = (String) jComboBoxMes.getSelectedItem();
        String hora = (String) jComboBoxHora.getSelectedItem();
        String minuto = (String) jComboBoxMinuto.getSelectedItem();
        String nombreEvento = jTextField1.getText();
        String tipoEvento = jTextField2.getText();
        int capacidad;
        double precio;
        
        try {
            capacidad = Integer.parseInt(jTextfieldCapacidad.getText());
            precio = Double.parseDouble(jTextfieldPrecio.getText());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Capacidad o precio no son válidos. Por favor, ingrese números válidos.");
            return;
        }

        String fechaCompleta = String.format("%s-%02d-%s %s:%s:00",
            anio,
            jComboBoxMes.getSelectedIndex() + 1,  // Asume que los índices del JComboBox corresponden a los meses del 1 al 12.
            dia,
            hora,
            minuto
        );

        // Instancia de la clase Eventos y llamada al método para agregar el evento.
        Eventos eventos = new Eventos();
        eventos.agregarEvento(nombreEvento, tipoEvento, fechaCompleta, capacidad, precio);

        // Limpia los campos después de la inserción
        Limpiar();
    }//GEN-LAST:event_jBtnAgregarActionPerformed

     private void Limpiar() {
        jTextDia.setText("");
        jTextAño.setText("");
        jComboBoxMes.setSelectedIndex(0);
        jComboBoxHora.setSelectedIndex(0);
        jComboBoxMinuto.setSelectedIndex(0);
        jTextField1.setText("");
        jTextField2.setText("");
        jTextfieldCapacidad.setText("");
        jTextfieldPrecio.setText("");
    }
