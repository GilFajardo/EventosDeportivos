    private void jbtnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnEliminarActionPerformed
String eventoId = jTextID.getText();
    if (eventoId.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Por favor, introduzca el ID del evento.");
        return;
    }

    // Solicitar credenciales del administrador
    String adminId = JOptionPane.showInputDialog(this, "Ingrese su ID de administrador:");
    if (adminId == null || adminId.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Eliminación cancelada, no se proporcionó ID de administrador.");
        return;
    }
    
    String adminPassword = JOptionPane.showInputDialog(this, "Ingrese su contraseña de administrador:");
    if (adminPassword == null || adminPassword.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Eliminación cancelada, no se proporcionó contraseña.");
        return;
    }

    // Llamada a la clase Eventos para eliminar el evento
    Eventos eventos = new Eventos();
    try {
        int id = Integer.parseInt(eventoId);
        eventos.eliminarEvento(id, adminId, adminPassword);
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "El ID proporcionado no es válido.");
    }       
    }//GEN-LAST:event_jbtnEliminarActionPerformed


