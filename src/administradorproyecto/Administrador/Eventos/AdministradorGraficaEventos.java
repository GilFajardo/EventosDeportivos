    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        DefaultCategoryDataset datosGrafica = new DefaultCategoryDataset();
    
        for (int i = 0; i < jTable1.getRowCount(); i++) {
            if (jTable1.getValueAt(i, 4) != null) {
                int asistencia = Integer.parseInt(jTable1.getValueAt(i, 4).toString());
                String evento = jTable1.getValueAt(i, 0).toString();
                String categoria = jTable1.getValueAt(i, 1).toString();
                datosGrafica.addValue(asistencia, categoria, evento);
            }
        }

        JFreeChart graficoBarras = ChartFactory.createBarChart3D(
                "Grafico de eventos",
                "Nombre de evento",
                "Asistencia",
                datosGrafica,
                PlotOrientation.VERTICAL,
                true,
                true,
                false
        );

        ChartPanel panel = new ChartPanel(graficoBarras);
        panel.setMouseWheelEnabled(true);
        panel.setPreferredSize(new Dimension(400, 200));

        jPanel1.removeAll(); // Limpiar el contenido anterior del jPanel1
        jPanel1.setLayout(new BorderLayout());
        jPanel1.add(panel, BorderLayout.NORTH);

        jPanel1.revalidate(); // Volver a validar el panel
        jPanel1.repaint(); // Repintar el panel para actualizarlo

        pack();
        repaint();
    }//GEN-LAST:event_jButton2ActionPerformed
    
    public void limpiarTabla(JTable tabla, DefaultTableModel modeloTabla){
        if(modeloTabla.getRowCount() > 0) {
            for(int i = 0; i < tabla.getRowCount(); i++){
                modeloTabla.removeRow(i);
            }
        }
    }

